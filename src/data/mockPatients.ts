// Helper to extract longitudinal trends across visits for any patient & parameter
export function extractParameterTrend(
  patient: Patient,
  parameterName: string
): ParameterTrendPoint[] {
  // Sort visits chronologically
  const sortedVisits = [...patient.visits].sort(
    (a, b) => new Date(a.date).getTime() - new Date(b.date).getTime()
  );

  const points: ParameterTrendPoint[] = [];

  for (const visit of sortedVisits) {
    const obs = visit.observations.find(
      (o) => o.parameter.toLowerCase() === parameterName.toLowerCase()
    );

    if (obs && typeof obs.numericValue === 'number') {
      points.push({
        visitDate: visit.date,
        visitId: visit.id,
        visitNumber: visit.visitNumber,
        value: obs.numericValue,
        displayValue: `${obs.value} ${obs.unit}`,
        unit: obs.unit,
        source: obs.source,
        flag: obs.flag,
      });
    }
  }

  return points;
}

